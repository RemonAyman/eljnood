export const getFaClass = (name) => {
  if (!name) return 'fa-solid fa-circle';
  const cleanName = String(name).trim();
  if (cleanName.startsWith('fa-') || cleanName.startsWith('fas ') || cleanName.startsWith('far ')) {
    return cleanName;
  }
  return FA_ICON_MAP[cleanName] || `fa-solid fa-${cleanName}`;
};

export const Icon = ({ name, className = '', ...props }) => {
  const faClass = getFaClass(name);
  return <i className={`${faClass} ${className}`} {...props}></i>;
};
